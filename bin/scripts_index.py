#!/usr/bin/env python3
"""bin/scripts_index.py [--check]: write SCRIPTS.md, one line per runnable script (a #! line): its path and the first
line of its usage header. --check exits 1 if SCRIPTS.md isn't what this would write (bin/test_scripts.sh runs it).

An agent reads SCRIPTS.md to find a script instead of searching the repo, then runs the script with no arguments for
its full usage instead of reading it.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

R = Path(__file__).resolve().parent.parent
OUT = R / "SCRIPTS.md"


def usage(p: Path) -> str:
    """The header's first sentence: comment or docstring lines after #! (and a uv script block), without the name."""
    text, lines = [], p.read_text(errors="replace").splitlines()[1:40]
    in_meta = in_doc = False
    for line in lines:
        s = line.strip()
        if s.startswith("# /// script"):
            in_meta = True
            continue
        if in_meta:
            in_meta = s != "# ///"
            continue
        if s.startswith('"""'):
            in_doc = not in_doc or s.count('"""') > 1
            s = s.strip('"').strip()
            if not s and in_doc:
                continue
        elif in_doc:
            pass
        elif s.startswith("#"):
            s = s.lstrip("#").strip()
        elif text or s.startswith(("from ", "import ", "set ")) or (s and not s.startswith("#")):
            break
        if not s:
            if text:
                break
            continue
        text.append(s)
        if re.search(r"[.:]\s*$", s) and len(" ".join(text)) > 40:
            break
    t = " ".join(text)
    t = re.sub(rf"^(\S*/)?{re.escape(p.name)}\b\s*", "", t).lstrip(": ")   # the name is the row's path already
    return (t[:117] + "...") if len(t) > 120 else t


def render() -> str:
    paths = subprocess.run(["git", "-C", str(R), "ls-files", "skills/*.sh", "bin/*.sh", "skills/*.py", "bin/*.py"],
                           capture_output=True, text=True, check=True).stdout.split()
    rows: dict[str, list[str]] = {}
    for rel in sorted(paths):
        p = R / rel
        if not p.read_text(errors="replace").startswith("#!"):
            continue
        group = "bin" if rel.startswith("bin/") else rel.split("/")[1]
        rows.setdefault(group, []).append(f"- `{rel}` {usage(p)}".rstrip())
    out = ["# Scripts", "",
           "Generated by `bin/scripts_index.py`; don't edit by hand. One line per runnable script: its path and the first",
           "line of its usage. Run a script with no arguments for its full usage instead of reading it.", ""]
    for g in sorted(rows, key=lambda g: (g != "bin", g)):
        out += [f"## {g}", "", *rows[g], ""]
    return "\n".join(out)


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == new
        print("SCRIPTS.md is current" if ok else "SCRIPTS.md is out of date: run bin/scripts_index.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(new)
    print(f"{OUT.relative_to(R)}: {new.count(chr(10) + '- ')} scripts, ~{len(new) // 4:,} tokens")
