#!/usr/bin/env bash
# connector-index.sh [--check]: the Lakeflow Connect connectors on docs.databricks.com, each with its doc pages and,
# for SaaS connectors, the ready-to-run pipeline notebook the docs publish. Writes ../references/connectors.md.
#
# Everything comes from the public docs: the sitemap lists every `ingestion/lakeflow-connect/<connector>-pipeline`
# page, and each pipeline page links its notebook (notebooks/source/saas-cdc/<connector>-pipeline.html, with an
# "open in Databricks" import button on the page). The connector's other pages (concepts, connection, limits, faq,
# reference, troubleshoot, source setup) are the sitemap entries that share its prefix. --check prints what would
# change instead of writing, and exits 1 if anything would.
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
OUT=$HERE/references/connectors.md
BASE=https://docs.databricks.com/aws/en
W=$(mktemp -d); trap 'rm -rf "${W:?}"' EXIT

curl -sSf --max-time 60 "$BASE/sitemap.xml" | grep -oE '<loc>[^<]+</loc>' | sed 's/<[^>]*>//g' |
  grep -E '/ingestion/lakeflow-connect/[a-z0-9-]+$' | sort -u > "$W/pages.txt"
grep -E -- '-pipeline$' "$W/pages.txt" > "$W/pipelines.txt"
[ -s "$W/pipelines.txt" ] || { echo "no lakeflow-connect pipeline pages in the sitemap"; exit 1; }

{
  echo "# Lakeflow Connect connectors in the Databricks docs"
  echo
  echo "Generated by [scripts/connector-index.sh](../scripts/connector-index.sh) from the public docs sitemap on $(date -u +%Y-%m-%d): every connector with an \`ingestion/lakeflow-connect/<connector>-pipeline\` page. **Status** is the badge under the page title (none means generally available). **Notebook** is the ready-to-run pipeline notebook the docs publish for the connector (fill in your connection and tables, or import it with the page's *Open in Databricks* button): start a test against a free developer org from it. Database connectors have no notebook."
  echo
  echo "| Connector | Status | Pipeline page | Notebook | Other pages |"
  echo "|---|---|---|---|---|"
  while read -r url; do
    slug=${url##*/}; prefix=${slug%-pipeline}
    curl -sS --max-time 30 "$url" > "$W/page.html" || { echo "| $prefix | [page]($url) | fetch failed | |"; continue; }
    name=$( (grep -oE '<title[^>]*>[^<]+' "$W/page.html" || true) | head -1 | sed -E 's/<[^>]*>//; s/ \| Databricks.*//; s/^(Ingest data from|Create an?|Ingest) //I; s/ (ingestion )?pipeline.*$//I')
    # status: the badge between the title and the first section ("This feature is in Beta"); none means generally
    # available. A badge further down is for one feature of the connector (Salesforce formula fields), not the page.
    status=$(tr '\n' ' ' < "$W/page.html" | sed -E 's|.*</h1>||; s|<h2.*||; s/<[^>]+>/ /g' | grep -oE 'This feature is in +[A-Z][A-Za-z]*( [A-Z][A-Za-z]*)?' | head -1 | sed -E 's/This feature is in +//' || true)
    nb=$(grep -oE 'notebooks(%2F|/)source(%2F|/)saas-cdc(%2F|/)[a-z0-9-]+\.html' "$W/page.html" | head -1 | sed 's|%2F|/|g' || true)
    others=$(grep -E "/lakeflow-connect/${prefix}-[a-z0-9-]+$" "$W/pages.txt" | grep -v -- "-pipeline$" |
      while read -r o; do printf '[%s](%s) ' "${o##*/"$prefix"-}" "$o"; done || true)
    echo "| ${name:-$prefix} | ${status:-GA} | [$slug]($url) | ${nb:+[notebook]($BASE/$nb)} | ${others% } |"
  done < "$W/pipelines.txt"
} > "$W/connectors.md"

if [ "${1:-}" = --check ]; then
  if [ -f "$OUT" ] && diff <(sed 1,4d "$OUT") <(sed 1,4d "$W/connectors.md") > /dev/null; then echo "up to date"; exit 0; fi
  diff <(sed 1,4d "$OUT" 2>/dev/null || true) <(sed 1,4d "$W/connectors.md") || true
  exit 1
fi
mv "$W/connectors.md" "$OUT"
echo "wrote $OUT: $(( $(grep -c '^| ' "$OUT") - 1 )) connectors, $(grep -c 'notebook](' "$OUT") with a notebook"
